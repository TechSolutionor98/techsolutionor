/**
 * Helper function to retrieve the technologies book data for any given service and language.
 * Falls back seamlessly to English if a requested language is not available,
 * and falls back to web-development if the serviceKey is unrecognized.
 */
export function getServiceTechnologies(serviceKey = "web-development", lang = "en") {
  const service = servicesTechnologiesData[serviceKey] || servicesTechnologiesData["web-development"];
  if (service[lang]) {
    return service[lang];
  }
  return service["en"] || servicesTechnologiesData["web-development"]["en"];
}
